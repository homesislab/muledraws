function breadcrumbs($data): string
{
	$result = [];
	foreach ($data as $row) {
		$url = '<span class="kt-subheader__breadcrumbs-separator"></span>';
		if ($row[1] == '#') {
			$url .= '<a href="#" class="kt-subheader__breadcrumbs-link">' . $row[0] . '</a>';
		} elseif ($row[1] == '') {
			$url .= '<a href="#" class="kt-subheader__breadcrumbs-link">' . $row[0] . '</a>';
		} else {
			$url .= '<a href="' . site_url($row[1]) . '" class="kt-subheader__breadcrumbs-link">' . $row[0] . '</a>';
		}
		array_push($result, $url);
	}
	return implode('', $result);
}

function removeComma($number, $delimiter = ','): string
{
	return str_replace($delimiter, '', $number);
}

function cloneTag($tag, $count): string
{
	$result = '';
	for ($i=1; $i <= $count; $i++) { 
		$result .= $tag;
	}
	return $result;
}

